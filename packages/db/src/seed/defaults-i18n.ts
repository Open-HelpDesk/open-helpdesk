/**
 * Translations of the example content installed in every new workspace.
 *
 * Why a table of its own, rather than the app's dictionaries: what
 * `installDefaults` writes is DATA, not labels. A policy called "Premium
 * customers" is a row an administrator renames, not a string the interface
 * looks up — so it has to be written in the workspace's language once, at
 * creation, and never translated again afterwards. `packages/db` also has no
 * business importing `apps/web/src/i18n`: it would invert the dependency, and
 * the same rows are read by the worker and the public API, which have no
 * locale at all.
 *
 * English is the fallback: a locale absent from a row falls back to `en`, so a
 * new language can ship its interface before its example content.
 *
 * The `{{contact.name}}` / `{{ticket.subject}}` placeholders are substituted at
 * send time and MUST be kept verbatim in every language.
 */

