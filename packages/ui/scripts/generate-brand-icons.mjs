/**
 * Generates the bundled brand-icon registry used by the service desk catalogue
 * (spec 19, D-SD7): `apps/web/src/components/desk/brand-icons.data.ts`.
 *
 * Only the brands listed in brand-icons.json are copied — a slug → { title, hex,
 * path } table — so the application never ships (or loads) the whole
 * simple-icons package, and never fetches a logo from a third party.
 *
 * simple-icons (CC0-1.0) removes brands at their owners' request (Slack,
 * Salesforce, Microsoft, Adobe… are gone). Those are listed under `colourOnly`:
 * the registry keeps their name and colour, and the tile shows initials.
 *
 * Usage: node packages/ui/scripts/generate-brand-icons.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const si = require("simple-icons");
const pkgDir = resolve(dirname(require.resolve("simple-icons")));
const { version } = JSON.parse(readFileSync(resolve(pkgDir, "package.json"), "utf8"));

const list = JSON.parse(readFileSync(resolve(here, "brand-icons.json"), "utf8"));
const bySlug = new Map(Object.values(si).map((icon) => [icon.slug, icon]));

const entries = [];
const missing = [];
for (const slug of list.icons) {
  const icon = bySlug.get(slug);
  if (!icon) {
    missing.push(slug);
    continue;
  }
  entries.push({ key: slug, title: icon.title, hex: `#${icon.hex}`, path: icon.path });
}
for (const [key, title, hex] of list.colourOnly) {
  if (bySlug.has(key)) throw new Error(`${key} exists in simple-icons ${version}: move it to "icons"`);
  entries.push({ key, title, hex, path: null });
}
if (missing.length) {
  throw new Error(`Not in simple-icons ${version}: ${missing.join(", ")} — move them to "colourOnly"`);
}
entries.sort((a, b) => a.key.localeCompare(b.key));

const out = resolve(here, "../../../apps/web/src/components/desk/brand-icons.data.ts");
const body = entries
  .map((e) => `  ${JSON.stringify(e.key)}: { title: ${JSON.stringify(e.title)}, hex: ${JSON.stringify(e.hex)}, path: ${JSON.stringify(e.path)} },`)
  .join("\n");
writeFileSync(
  out,
  `/* GENERATED by packages/ui/scripts/generate-brand-icons.mjs — do not edit.
 * Brand glyphs from simple-icons ${version} (CC0-1.0, https://simpleicons.org).
 * Brand names and logos remain trademarks of their owners.
 * To add a brand: edit packages/ui/scripts/brand-icons.json and re-run the script. */
export type BrandIconData = { title: string; hex: string; path: string | null };

export const BRAND_ICON_DATA: Record<string, BrandIconData> = {
${body}
};
`,
);
console.log(`${entries.length} brands (${entries.filter((e) => e.path).length} with a glyph) → ${out}`);
